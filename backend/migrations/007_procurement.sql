  created_by_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_webhooks_org ON webhooks (org_id);

CREATE TYPE webhook_delivery_status AS ENUM ('pending', 'success', 'failed');

CREATE TABLE webhook_deliveries (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id          uuid NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  webhook_id      uuid NOT NULL REFERENCES webhooks(id) ON DELETE CASCADE,
  event           text NOT NULL,
  payload         jsonb NOT NULL,
  signature       text NOT NULL,
  status          webhook_delivery_status NOT NULL DEFAULT 'pending',
  attempts        int NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_http_status int,
  last_error      text,
  -- NULL on terminal rows (success/failed): no retry scheduled.
  next_attempt_at timestamptz DEFAULT now(),
  delivered_at    timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_webhook_deliveries_pending ON webhook_deliveries (org_id, status, next_attempt_at);

-- ---- Supplier scorecard (derived, never stored) ----------------------------
-- Per-PO metrics are aggregated in LATERAL subqueries so a PO with several
-- GRNs (split deliveries) never double-counts its line values.
CREATE VIEW v_supplier_scorecard
WITH (security_invoker = true) AS
WITH po_metrics AS (
  SELECT po.supplier_id, po.org_id,
         COUNT(*) FILTER (WHERE po.status <> 'draft')::int AS po_count,
         COUNT(*) FILTER (WHERE po.status = 'received')::int AS fully_received_count,
         COUNT(*) FILTER (WHERE po.status IN ('partially_received', 'received'))::int AS partially_or_fully_received_count,
         COALESCE(SUM(plv.value), 0)::numeric(14,4) AS total_ordered_value,
         COALESCE(SUM(glv.value), 0)::numeric(14,4) AS total_received_value,
         AVG(EXTRACT(EPOCH FROM (gr.first_received_at - po.sent_at)) / 86400.0) AS avg_lead_time_days,
         COUNT(*) FILTER (WHERE po.expected_delivery IS NOT NULL
                            AND po.status IN ('partially_received', 'received')
                            AND gr.first_received_at::date <= po.expected_delivery)::int AS on_time_count,
         COUNT(*) FILTER (WHERE po.expected_delivery IS NOT NULL
                            AND po.status IN ('partially_received', 'received'))::int AS due_count
  FROM purchase_orders po
  LEFT JOIN LATERAL (
    SELECT MIN(g.received_at) AS first_received_at
    FROM goods_receipts g
    WHERE g.po_id = po.id
  ) gr ON true
  LEFT JOIN LATERAL (
    SELECT SUM(pl.quantity * pl.unit_cost) AS value
    FROM purchase_order_lines pl
    WHERE pl.purchase_order_id = po.id
  ) plv ON true
  LEFT JOIN LATERAL (
    SELECT SUM(gl.quantity * gl.unit_cost) AS value
    FROM goods_receipts g
    JOIN goods_receipt_lines gl ON gl.goods_receipt_id = g.id
    WHERE g.po_id = po.id
  ) glv ON true
  GROUP BY po.supplier_id, po.org_id
)
SELECT s.id AS supplier_id, s.name AS supplier_name, s.code AS supplier_code,
       COALESCE(pm.po_count, 0)::int AS po_count,
       COALESCE(pm.fully_received_count, 0)::int AS fully_received_count,
       COALESCE(pm.partially_or_fully_received_count, 0)::int AS partially_or_fully_received_count,
       COALESCE(pm.total_ordered_value, 0)::numeric(14,4) AS total_ordered_value,
       COALESCE(pm.total_received_value, 0)::numeric(14,4) AS total_received_value,
       ROUND(pm.avg_lead_time_days::numeric, 1) AS avg_lead_time_days,
       CASE WHEN COALESCE(pm.due_count, 0) = 0 THEN NULL
            ELSE ROUND((pm.on_time_count::numeric / pm.due_count), 2)
       END AS on_time_rate
FROM suppliers s
LEFT JOIN po_metrics pm ON pm.supplier_id = s.id AND pm.org_id = s.org_id;

